/** Dusk, step two: lay the trap kits on the road and put a crew on each gun nest. Then the night. */
function deployStep() {
  migrateTraps();
  const stock = G.trapStock ?? {};
  const emps = parseEmplacements(G.flags.emplacements).filter((e) => EMPLACEMENTS[e.id]?.crew);
  const kits = Object.values(stock).some((v) => v > 0);
  const fighters = living().filter(canFight);
  const guards = fighters.filter((s) => !s.isLeader).slice(0, 5);
  if (!kits && !emps.length && !guards.length) return night();
  app.onclick = null;
  app.onchange = null;
  app.innerHTML = `<div class="deploywrap" style="background-image:linear-gradient(rgba(10,9,8,.84),rgba(10,9,8,.95)),url(${spriteUrl('bg_far')})"><div class="dep-posts"></div><div class="dep-crew"></div><div class="dep-root"></div></div>`;
  const postsEl = app.querySelector('.dep-posts') as HTMLElement;
  const crewEl = app.querySelector('.dep-crew') as HTMLElement;
  const rootEl = app.querySelector('.dep-root') as HTMLElement;
  // ---- where each guard stands (night/battle.ts Post); the roof nest if there is one ----
  const NEST_COST = { wood: 12, scrap: 4 } as const;
  const renderPosts = () => {
    if (!guards.length) { postsEl.innerHTML = ''; return; }
    let saved: Record<string, GuardPost> = {};
    try { saved = G.flags.posts ? JSON.parse(G.flags.posts as string) as Record<string, GuardPost> : {}; } catch { saved = {}; }
    const nest = !!G.flags.roofNest || G.buildings.some((b) => b.id === 'roofnest');
    const opts: GuardPost[] = ['step', 'loop', 'runner', ...(nest ? ['roof' as GuardPost] : [])];
    const hint: Record<GuardPost, string> = { step: 'shoots over the wall', loop: 'a shotgun at the loophole: shoves harder; gets clawed by big ones', runner: 'carries ammo: everyone reloads faster; shoots only what gets over', roof: 'sees farther and steadier; cannot angle down at the wall' };
    const canNest = !nest && (G.stores.wood ?? 0) >= NEST_COST.wood && (G.stores.scrap ?? 0) >= NEST_COST.scrap;
    postsEl.innerHTML = `<div class="dep posts"><header class="dep-h"><h2>Posts</h2><span class="dep-count">one at the loophole, one on the roof</span></header>
      ${guards.map((s) => {
        const w = G.weapons.find((x) => x.uid === s.weapon);
        const cur = saved[s.id] && opts.includes(saved[s.id]) ? saved[s.id] : '';
        return `<p class="postrow"><b>${esc(first(s))}</b> <span class="dim">${w ? esc(w.name ? `"${w.name}"` : WEAPONS[w.def]?.name.toLowerCase() ?? w.def) : 'no gun'}</span>
          <select data-post="${esc(s.id)}"><option value="" ${cur ? '' : 'selected'}>let them choose</option>${opts.map((p) => `<option value="${p}" ${p === cur ? 'selected' : ''}>${POST_NAMES[p]}</option>`).join('')}</select>
          <span class="dim">${cur ? esc(hint[cur]) : ''}</span></p>`;
      }).join('')}
      <p class="postrow">${nest ? '<span class="dim">The roof nest is up on the garage.</span>' : `<button type="button" class="mini" data-nest ${canNest ? '' : 'disabled'}>Throw up a roof nest now</button> <span class="dim">${NEST_COST.wood} timber, ${NEST_COST.scrap} scrap (cheaper at the workbench)</span>`}</p></div>`;
  };
  const readPosts = () => {
    if (!guards.length) return;
    const posts: Record<string, GuardPost> = {};
    const taken = new Set<GuardPost>();
    for (const el of Array.from(postsEl.querySelectorAll<HTMLSelectElement>('[data-post]'))) {
      let p = el.value as GuardPost | '';
      if (!p) continue;
      if ((p === 'loop' || p === 'roof') && taken.has(p)) p = 'step';
      taken.add(p);
      posts[el.dataset.post!] = p;
    }
    if (Object.keys(posts).length) {
      // anyone left to choose stands the firestep
      for (const s of guards) posts[s.id] ??= 'step';
      G.flags.posts = JSON.stringify(posts);
    } else delete G.flags.posts;
  };
  renderPosts();
  postsEl.addEventListener('change', (e) => { sfx.ui(); readPosts(); renderPosts(); void e; });
  postsEl.addEventListener('click', (e) => {
    if (!(e.target as HTMLElement).closest('[data-nest]')) return;
    if ((G.stores.wood ?? 0) < NEST_COST.wood || (G.stores.scrap ?? 0) < NEST_COST.scrap) return;
    readPosts();
    add('wood', -NEST_COST.wood);
    add('scrap', -NEST_COST.scrap);
    G.flags.roofNest = 1;
    report.push('Planks and sandbags went up on the garage roof at dusk: a nest for one rifle.');
    sfx.ui('stamp');
    renderPosts();
  });
  const plan = crewPlan();
  if (emps.length) {
    crewEl.innerHTML = `<div class="dep crew"><header class="dep-h"><h2>The guns</h2><span class="dep-count">heavy-weapons training decides how well a crew works one</span></header>
      ${emps.map((e, i) => {
        const d = EMPLACEMENTS[e.id];
        const want = plan[String(i)] ?? 'auto';
        return `<p class="crewrow"><b>${esc(d.name)}</b>
          <span class="dim">${Math.round(e.cond * 100)}%</span>
          <label>post <select data-emp-post="${i}">${d.posts.map((p) => `<option value="${p}" ${p === e.post ? 'selected' : ''}>${p === 'roof' ? 'roof scaffold' : 'firestep'}</option>`).join('')}</select></label>
          <label>crew <select data-emp-crew="${i}">
            <option value="auto" ${want === 'auto' ? 'selected' : ''}>best heavy-trained</option>
            <option value="none" ${want === 'none' ? 'selected' : ''}>nobody (I'll take it: [H])</option>
            ${fighters.map((s) => `<option value="${esc(s.id)}" ${want === s.id ? 'selected' : ''}>${esc(first(s))} · heavy ${level(s, 'heavy')}${s.isLeader ? ' (you)' : ''}</option>`).join('')}
          </select></label>
          <span class="dim">${esc(d.niche)}</span></p>`;
      }).join('')}</div>`;
  }
  const readCrew = () => {
    if (!emps.length) return;
    const crew: Record<string, string> = {};
    const all = parseEmplacements(G.flags.emplacements);
    let k = 0;
    all.forEach((it) => {
      if (!EMPLACEMENTS[it.id]?.crew) return;
      const i = k++;
      const c = crewEl.querySelector(`[data-emp-crew="${i}"]`) as HTMLSelectElement | null;
      const p = crewEl.querySelector(`[data-emp-post="${i}"]`) as HTMLSelectElement | null;
      if (c) crew[String(i)] = c.value;
      if (p) it.post = p.value as Post;
    });
    G.flags.empCrew = JSON.stringify(crew);
    G.flags.emplacements = stringifyEmplacements(all);
  };
  const finish = (ps: Placement[]) => {
    readCrew();
    readPosts();
    // the electric fence needs the generator and a can of fuel a night
    const kept: Placement[] = [];
    const dropped: string[] = [];
    for (const p of ps) {
      const t = TRAPS[p.trap];
      if (!t) continue;
      if (t.requires?.building && !buildingLevel(t.requires.building)) { dropped.push(`${t.name} (no ${t.requires.building})`); continue; }
      const up = Object.entries(t.upkeep ?? {}) as [keyof typeof G.stores, number][];
      if (up.some(([k, v]) => (G.stores[k] ?? 0) < v)) { dropped.push(`${t.name} (no fuel)`); continue; }
      for (const [k, v] of up) add(k, -v);
      kept.push(p);
    }
    G.deploy = kept;
    G.trapStock = spendStock(stock, kept);
    G.flags.lastPlan = JSON.stringify(kept);
    if (dropped.length) report.push(`Left in the shed tonight: ${dropped.join(', ')}.`);
    save();
    night();
  };
  if (kits) {
    let last: Placement[] = [];
    try { last = JSON.parse((G.flags.lastPlan as string) ?? '[]'); } catch { last = []; }
    const left: Record<string, number> = { ...stock };
    const bestBuilding = Math.max(0, ...living().map((s) => s.skills.building ?? 0));
    const allowed = placementsAllowed(bestBuilding);
    // last night's plan, as far as the kits on hand and tonight's hands allow
    const initial = last.filter((p) => TRAPS[p.trap] && (left[p.trap] = (left[p.trap] ?? 0) - 1) >= 0).slice(0, allowed);
    renderDeploy(rootEl, {
      stock, laneCount: 4, roadMinX: WALL_X, roadMaxX: ROAD_MAX_X, wallX: WALL_X,
      placementsAllowed: allowed, initial, title: `Dusk, ${dateLabel()}. The road.`,
      onDone: (ps) => finish(ps.slice(0, allowed)),
    });
  } else {
    rootEl.innerHTML = '<div class="dep dep-end"><button type="button" class="dep-done">To the wall. Night falls.</button></div>';
    rootEl.querySelector('.dep-done')!.addEventListener('click', () => { sfx.ui(); finish([]); });
  }
}

