const app = document.getElementById('app')!;
let report: string[] = [];
let battle: Battle | null = null;

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

function title() {
  music('title');
  const saved = loadSave();
  app.innerHTML = `<div class="title" style="background-image:linear-gradient(rgba(8,8,10,.35),rgba(8,8,10,.92)),url(${spriteUrl('bg_sky')})">
    <div class="tbox">
      <h1>VESSEY</h1>
      <div class="tsub">before the ice</div>
      <p class="tquote">"IT'S IN THE WATER / IT'S IN THE DEER / IT'S IN US<br>RIVER FREEZES NOV 28 — GET ACROSS OR GET READY"<br><span>— spray paint, Vessey water tower</span></p>
      ${saved ? `<button data-act="continue">Continue — ${dateLabel(saved.day)}, ${saved.survivors.filter((s) => !s.dead).length} living</button>` : ''}
      <div class="personas">${Object.values(PERSONAS).map((p) => `<button data-act="new" data-id="${p.id}"><b>${p.name}</b><small>${p.desc}</small></button>`).join('')}</div>
      <p class="how">A paper-mill town on the St. Aubin River, November. The Guard sealed the bridge. Hold a house on Ferry Road with whoever you can find.<br>
      <b>Day:</b> assign survivors, scavenge, build machinery, craft. <b>Night:</b> aim with the mouse, click to fire, aim for the head. [R] reload, [Q] swap, [F] firebomb.</p>
      <div class="tbtns"><button class="mute" data-act="mute" aria-pressed="${muted}">${muted ? 'sound off' : 'sound on'}</button><button class="mute" data-act="settings">settings</button><button class="mute" data-act="help">how to play</button></div>
      <p class="credits">Art generated; story generated by you.</p>
    </div>
  </div>`;
  startAsh(app.querySelector('.title') as HTMLElement);
  app.onclick = (e) => {
    const el = (e.target as HTMLElement).closest('[data-act]') as HTMLElement | null;
    if (!el) return;
    sfx.ui();
    if (el.dataset.act === 'continue' && saved) {
      setState(saved);
      report = ['You return to the house on Ferry Road.'];
      if (G.phase === 'over') return G.flags.ending ? epilogue() : gameOver();
      day();
    } else if (el.dataset.act === 'new') {
      clearSave();
      newGame(el.dataset.id);
      report = [
        `${displayName(living()[0])} leads. ${living().slice(1).map(displayName).join(' and ')} came with ${living()[0].sex === 'm' ? 'him' : 'her'}.`,
        'Assign everyone a job for the day, then go to the wall at dusk.',
      ];
      save();
      day();
    } else if (el.dataset.act === 'mute') {
      setMuted(!muted);
      title();
    } else if (el.dataset.act === 'settings') openSettings(app);
    else if (el.dataset.act === 'help') openHelp(app, 'night');
  };
}

function day() {
  music('day');
  G.phase = 'day';
  app.onclick = null;
  app.onchange = null;
  renderDay(app, {
    rerender: () => day(),
    onChoice: (i) => {
      const ev = G.pendingEvent;
      if (!ev) return;
      G.pendingEvent = null;
      const outcome = resolveEvent(ev, i);
      if (outcome) report.push(outcome);
      // an incident can end the story (the ferry, the mill)
      if (G.flags.ending) return epilogue();
      // events can chain (e.g. found survivor + a bite)
      if (!living().length) return gameOver();
      save();
      day();
    },
    onDusk: () => dusk(),
    onRun: (site) => run(site),
  }, report);
}

function run(site: string) {
  const l = living().find((s) => s.isLeader);
  if (!l) return;
  G.flags.ranToday = G.day;
  l.job = 'rest';
  save();
  app.onclick = null;
  app.onchange = null;
  app.innerHTML = `<div class="stage"><canvas width="${W}" height="${H}"></canvas></div>`;
  const ex = new Expedition(app.querySelector('canvas')!, l, site, (r) => afterRun(r));
  ex.start();
}

function afterRun(r: ExpeditionResult) {
  const lines: string[] = [];
  const loot = Object.entries(r.loot).filter(([, v]) => v).map(([k, v]) => `${v} ${k}`).join(', ');
  if (r.died) lines.push('They did not come back. Whatever they carried is out there in the road.');
  else lines.push(loot ? `Brought home: ${loot}.` : 'Came home empty-handed.');
  if (r.found) {
    G.survivors.push(r.found);
    log('arrival', `${displayName(r.found)} came home with the run. ${r.found.before}`);
    lines.push(`${displayName(r.found)} came back too. ${r.found.before}`);
  }
  lines.push(...r.lines);
  report.push(...lines);
  save();
  if (!living().length) return gameOver();
  day();
  overlay(`<h2>${r.died ? 'Lost' : 'Back before dark'}</h2>${lines.map((x) => `<p>${esc(x)}</p>`).join('')}`, () => day());
}

function overlay(html: string, onClose: () => void) {
  const div = document.createElement('div');
  div.className = 'overlay';
  div.innerHTML = `<div class="modal">${html}<button class="go">Continue ›</button></div>`;
  app.appendChild(div);
  div.querySelector('.go')!.addEventListener('click', () => {
    sfx.ui();
    div.remove();
    onClose();
  });
}

function dusk() {
  const lines = resolveDayWork();
  const plan = planNight();
  G.nextNight = plan;
  save();
  overlay(`<h2>Dusk, ${dateLabel()}</h2>${lines.map((l) => `<p>${esc(l)}</p>`).join('')}<p class="forecast">${esc(plan.label)}</p>`, () => night());
}

function night() {
  music('night');
  G.phase = 'night';
  app.onclick = null;
  app.onchange = null;
  app.innerHTML = `<div class="stage"><canvas width="${W}" height="${H}"></canvas></div>`;
  const canvas = app.querySelector('canvas')!;
  battle = new Battle(canvas, G.nextNight!, (r) => dawn(r));
  battle.start();
}

function dawn(r: NightResult) {
  battle = null;
  afterNight(r.deaths.length, r.wallHeld);
  if (r.fell) {
    // the house is overrun; those inside may not make it
    for (const s of living()) {
      if (Math.random() < 0.6) {
        s.dead = { day: G.day, cause: 'when the house on Ferry Road was overrun', epitaph: s.tales[s.tales.length - 1] ?? 'Was there at the end.' };
        G.graves.push(s);
      }
    }
    G.survivors = G.survivors.filter((s) => !s.dead);
  }
  const wasIce = G.day === ICE_DAY;
  const lines: string[] = [];
  lines.push(`${r.kills} of the Turned put down.${r.headshots ? ` ${r.headshots} through the head.` : ''}`);
  if (r.deaths.length) lines.push(`We lost ${r.deaths.join(', ')}.`);
  if (!r.wallHeld) lines.push('They came over the wall.');
  lines.push(...r.lines);
  // morning report: who carried the night, who broke
  const panicked = living().filter((s) => G.chronicle.some((e) => e.day === G.day && e.kind === 'break' && e.text.startsWith(displayName(s)) && e.text.includes('panicked')));
  lines.push(...morningSummary(r.killsBy, [...living(), ...G.graves], panicked, r.deaths));
  const used = Object.entries(r.ammoUsed).map(([k, v]) => `${v} ${k === 'light' ? 'pistol rounds' : k === 'shell' ? 'shells' : k === 'rifle' ? 'rifle rounds' : k}`).join(', ');
  if (used) lines.push(`Spent: ${used}.`);
  if (!living().length) return gameOver();
  G.day++;
  nextWeather();
  const morning = [...returnsTick(), ...dawnTick()];
  if (!living().length) return gameOver();
  report = [...lines, ...morning];
  // holding: forty days on Ferry Road is the third way out
  if (G.day >= SPRING_DAY) {
    G.flags.ending = 'spring';
    G.flags.endWent = JSON.stringify(living().map((s) => s.id));
    log('event', 'The fortieth morning. We are still here.');
    return epilogue();
  }
  G.pendingEvent = rollIncident();
  save();
  if (wasIce) return iceEpilogue(r.fell);
  overlay(`<h2>Dawn, ${dateLabel()}</h2>${report.map((l) => `<p>${esc(l)}</p>`).join('')}`, () => day());
}

function iceEpilogue(fell: boolean) {
  const alive = living();
  log('lore', fell ? 'The river froze. They walked across it and through our house. Some of us lived.' : 'The river froze. They walked across it in the night, and we were still here in the morning.');
  overlay(`<h2>The river is ice</h2>
    <p>They came across the St. Aubin in the dark, hundreds of them, the ice booming under their weight. ${fell ? 'They went through the house on Ferry Road like water through a net. Whoever lived did it hiding in the root cellar, listening to them walk overhead until dawn.' : 'In the morning the house on Ferry Road was still standing.'}</p>
    <p>${alive.map((s) => esc(displayName(s))).join(', ')} saw the first light of December.</p>
    <p>${G.graves.length ? `Behind the house: ${G.graves.map((g) => esc(first(g))).join(', ')}.` : 'Nobody is buried behind the house. Nobody.'}</p>
    <p class="forecast">The ice will hold until April. Winter has only begun. (The game continues as long as you can hold.)</p>`, () => day());
}

const SPRING_DAY = 40;

const ENDINGS: Record<string, { title: string; text: (went: Survivor[], stayed: Survivor[]) => string }> = {
  ferry: {
    title: 'The last crossing',
    text: (went, stayed) => `At two in the morning the Doucette boat pushed off from the landing below Ferry Road with ${went.length} of us aboard, low in the black water, ice already whispering against the hull at the edges. Marie Doucette ran without lights. We passed Grace Island close enough to hear something moving on the shore, and then the east channel, and then the place where the Line should have been and wasn't.${stayed.length ? ` Behind us, a lamp burned in the window of the house on Ferry Road. ${stayed.map(first).join(' and ')} kept it lit.` : ' Behind us, the house on Ferry Road went dark for the first time in weeks.'} Four days later the St. Aubin froze from bank to bank.`,
  },
  mill: {
    title: 'The mill',
    text: (went, stayed) => `We walked two miles up Mill Road in the snow, ${went.length} of us, carrying everything that would carry. The Local 41 gate opened before we knocked. Inside there was steam heat and the smell of wet pulp and a chalkboard that said EVERYBODY WORKS A SHIFT, and Dolores Wick wrote our names on it, one under the other.${stayed.length ? ` ${stayed.map(first).join(' and ')} stayed behind in the house on Ferry Road, because the Union does not take the bitten. Nobody ever went back to see.` : ''} The boilers ran until April.`,
  },
  spring: {
    title: 'Spring',
    text: (went) => `Forty days. Then fifty. The ice held and the dead came across it every night and every night the wall on Ferry Road held, more or less. In January the radio stopped looping. In March it said something new. On the ninth of April the St. Aubin broke up with a sound like artillery, and the ice went out, and ${went.length ? went.map(first).join(', ') : 'nobody'} stood on the porch of the brick house and watched it go.`,
  },
};

function epilogue() {
  G.phase = 'over';
  G.pendingEvent = null;
  save();
  music('title');
  const ending = String(G.flags.ending);
  const E = ENDINGS[ending] ?? ENDINGS.spring;
  const went = parseIds(G.flags.endWent).map((id) => byId(id)).filter((s): s is Survivor => !!s && !s.dead);
  const stayed = parseIds(G.flags.endStayed).map((id) => byId(id)).filter((s): s is Survivor => !!s && !s.dead);
  const fates: { s: Survivor; f: Fate }[] = [
    ...went.map((s) => ({ s, f: (ending === 'spring' ? 'held' : 'went') as Fate })),
    ...stayed.map((s) => ({ s, f: 'stayed' as Fate })),
    ...G.graves.map((s) => ({ s, f: (s.dead?.cause === 'deserted' ? 'left' : 'dead') as Fate })),
  ];
  const card = (x: { s: Survivor; f: Fate }) => {
    const s = x.s;
    const label = x.f === 'dead' ? 'buried' : x.f === 'left' ? 'gone' : x.f === 'stayed' ? 'stayed behind' : 'lived';
    return `<div class="grave"><div class="gn">${esc(displayName(s))}</div>
      <div class="gd">${s.age}${s.child ? ' (a child)' : ''} · ${s.kills} put down · ${s.daysSurvived} days · <b>${label}</b></div>
      <div class="ge">${esc(fateLine(s, x.f, ending))}</div>
      ${s.tales.length ? `<ul>${s.tales.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>` : ''}</div>`;
  };
  app.onclick = null;
  app.onchange = null;
  app.innerHTML = `<div class="over epilogue" data-ending="${esc(ending)}">
    <h1>${esc(E.title)}</h1>
    <p class="sub">${dateLabel(1)} – ${dateLabel()} · ${G.day} days · ${G.stats.kills} of the Turned put down · ${G.stats.headshots} headshots</p>
    <p class="epi" style="max-width:46em;margin:1em auto;line-height:1.55">${esc(E.text(went, stayed))}</p>
    <h2>What became of them</h2>
    <div class="graves">${fates.map(card).join('')}</div>
    <h2>The chronicle</h2>
    <div class="chron">${G.chronicle.map((e) => `<p class="ce ${e.kind}"><b>${dateLabel(e.day)}.</b> ${esc(e.text)}</p>`).join('')}</div>
    <button data-act="again">Begin again</button>
  </div>`;
  app.onclick = (e) => {
    if ((e.target as HTMLElement).dataset.act === 'again') {
      clearSave();
      title();
    }
  };
}

function gameOver() {
  G.phase = 'over';
  save();
  const all = [...G.graves];
  app.onclick = null;
  app.innerHTML = `<div class="over">
    <h1>The house on Ferry Road</h1>
    <p class="sub">${dateLabel(1)} – ${dateLabel()} · ${G.day} days · ${G.stats.kills} of the Turned put down · ${G.stats.headshots} headshots</p>
    <div class="graves">${all.map((g) => `<div class="grave"><div class="gn">${esc(displayName(g))}</div>
      <div class="gd">${g.age} · ${g.kills} put down · ${g.daysSurvived} days</div>
      <div class="gc">${esc(g.dead?.cause ?? '')}</div>
      <div class="ge">${esc(g.dead?.epitaph ?? '')}</div>
      ${g.tales.length ? `<ul>${g.tales.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>` : ''}</div>`).join('')}</div>
    <h2>The chronicle</h2>
    <div class="chron">${G.chronicle.map((e) => `<p class="ce ${e.kind}"><b>${dateLabel(e.day)}.</b> ${esc(e.text)}</p>`).join('')}</div>
    <button data-act="again">Begin again</button>
  </div>`;
  app.onclick = (e) => {
    if ((e.target as HTMLElement).dataset.act === 'again') {
      clearSave();
      title();
    }
  };
}

