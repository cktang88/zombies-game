function day() {
  music('day');
  ambience('day');
  G.phase = 'day';
  app.onclick = null;
  app.onchange = null;
  renderDay(app, {
    rerender: () => day(),
    onChoice: (i) => {
      const ev = G.pendingEvent;
      if (!ev) return;
      G.pendingEvent = null;
      const outcome = resolveEvent(ev, i);
      if (outcome) report.push(outcome);
      // an incident can end the story (the ferry, the mill)
      if (G.flags.ending) return epilogue();
      // events can chain (e.g. found survivor + a bite)
      if (!living().length) return gameOver();
      save();
      day();
    },
    onDusk: () => dusk(),
    onRun: (site) => run(site),
  }, report);
}

function run(site: string) {
  const l = living().find((s) => s.isLeader);
  if (!l) return;
  if (G.flags.ranToday !== G.day) prepareRun(site, 0); // the day screen normally books it (leave time, runDaylight)
  save();
  app.onclick = null;
  app.onchange = null;
  app.innerHTML = `<div class="stage"><div class="pf"><canvas width="${W}" height="${H}"></canvas></div></div>`;
  ambience('run');
  const ex = new Expedition(app.querySelector('canvas')!, l, site, (r) => afterRun(r));
  ex.start();
  mountStage(app.querySelector('.stage')!, 'run');
}

function afterRun(r: ExpeditionResult) {
  restoreRunMate();
  const lines: string[] = [];
  const loot = Object.entries(r.loot).filter(([, v]) => v).map(([k, v]) => `${v} ${k}`).join(', ');
  if (r.died) lines.push('They did not come back. Whatever they carried is out there in the road.');
  else lines.push(loot ? `Brought home: ${loot}.` : 'Came home empty-handed.');
  if (r.found) {
    G.survivors.push(r.found);
    log('arrival', `${displayName(r.found)} came home with the run. ${r.found.before}`);
    lines.push(`${displayName(r.found)} came back too. ${r.found.before}`);
  }
  lines.push(...r.lines);
  const l = G.survivors.find((s) => s.isLeader && !s.dead);
  if (l && !r.died) {
    gainXp(l, 'scavenging', 40);
    gainXp(l, 'grit', 15);
  }
  lines.push(...drainLevelUps());
  report.push(...lines);
  save();
  if (!living().length) return gameOver();
  day();
  overlay(`<h2>${r.died ? 'Lost' : 'Back before dark'}</h2>${lines.map((x) => `<p>${esc(x)}</p>`).join('')}`, () => day());
}

