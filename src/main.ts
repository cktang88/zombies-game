function epilogue() {
  G.phase = 'over';
  G.pendingEvent = null;
  const fresh = recordRun('ending');
  save();
  music('title');
  ambience('title');
  const ending = String(G.flags.ending);
  const E = ENDINGS[ending] ?? ENDINGS.spring;
  const went = parseIds(G.flags.endWent).map((id) => byId(id)).filter((s): s is Survivor => !!s && !s.dead);
  const stayed = parseIds(G.flags.endStayed).map((id) => byId(id)).filter((s): s is Survivor => !!s && !s.dead);
  const cards: Card[] = [
    ...went.map((s) => ({ s, f: (ending === 'spring' || ending === 'ice' ? 'held' : 'went') as Fate })),
    ...stayed.map((s) => ({ s, f: 'stayed' as Fate })),
    ...evacuees().map((s) => ({ s, f: 'went' as Fate })),
    ...graveCards(),
  ];
  const ev = evacuees();
  endRender = () => endScreen({
    title: E.title, cls: 'epilogue', ending, fresh,
    intro: E.text(went, stayed) + (ev.length ? ` Somewhere downriver, ${ev.map(first).join(' and ')} got off Old Peltier's boat at his sister's dock in Ashby, and never once spoke about the seat.` : ''),
    cards,
    buttons: '<div class="endchoice"><button class="go" data-act="again">Begin again</button></div>',
  });
  endRender();
}

function gameOver() {
  G.phase = 'over';
  const fresh = recordRun('dead');
  save();
  endRender = () => endScreen({
    title: 'The house on Ferry Road', ending: '', fresh,
    intro: evacuees().length ? `Nobody is left in the house on Ferry Road. ${evacuees().map(first).join(' and ')} got out on Old Peltier's boat, and lived.` : '',
    cards: [...evacuees().map((s) => ({ s, f: 'went' as Fate })), ...graveCards()],
    buttons: '<div class="endchoice"><button class="go" data-act="again">Begin again</button></div>',
  });
  endRender();
}

